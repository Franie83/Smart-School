/**
 * Generate initial attendance records for several school days in Sep 2026
 * Dates:
 * - 2026-09-07 (Mon)
 * - 2026-09-08 (Tue)
 * - 2026-09-09 (Wed)
 * - 2026-09-10 (Thu)
 * - 2026-09-11 (Fri)
 * - 2026-09-14 (Mon)
 * - 2026-09-15 (Tue)
 * - 2026-09-16 (Wed)
 * - 2026-09-17 (Thu)
 * - 2026-09-18 (Fri)
 * - 2026-09-21 (Mon)
 * - 2026-09-22 (Tue)
 * - 2026-09-23 (Wed)
 * - 2026-09-24 (Thu)
 * - 2026-09-25 (Fri)
 * - 2026-09-28 (Mon)
 * - 2026-09-29 (Tue) [Today]
 */
export function generateInitialAttendanceRecords(): AttendanceRecord[] {
  const dates = [
    '2026-09-07',
    '2026-09-08',
    '2026-09-09',
    '2026-09-10',
    '2026-09-11',
    '2026-09-14',
    '2026-09-15',
    '2026-09-16',
    '2026-09-17',
    '2026-09-18',
    '2026-09-21',
    '2026-09-22',
    '2026-09-23',
    '2026-09-24',
    '2026-09-25',
    '2026-09-28',
    '2026-09-29',
  ];

  const records: AttendanceRecord[] = [];

  for (const date of dates) {
    for (const student of INITIAL_STUDENTS) {
      // Don't mark attendance before admission
      if (student.dateOfAdmission && date < student.dateOfAdmission) {
        continue;
      }
      // Don't mark attendance after withdrawal
      if (student.dateOfWithdrawal && date > student.dateOfWithdrawal) {
        continue;
      }

      let mStatus: 'PRESENT' | 'ABSENT' | 'EXCUSED' = 'PRESENT';
      let aStatus: 'PRESENT' | 'ABSENT' | 'EXCUSED' = 'PRESENT';
      let mLate: 'ON_TIME' | 'LATE' = 'ON_TIME';
      let aLate: 'ON_TIME' | 'LATE' = 'ON_TIME';
      let note: string | undefined = undefined;

      // Deterministic realistic variance based on student & date
      const hash = (student.id.charCodeAt(4) || 1) * 31 + new Date(date).getDate();

      // Stu 3 (Toluwalase) sometimes arrives late
      if (student.id === 'stu_3' && (hash % 4 === 0)) {
        mLate = 'LATE';
      }

      // Stu 5 (Emeka) absent once in a while
      if (student.id === 'stu_5' && (hash % 7 === 0)) {
        mStatus = 'ABSENT';
        aStatus = 'ABSENT';
      }

      // Stu 7 (Babatunde) morning present, afternoon absent on certain days
      if (student.id === 'stu_7' && date === '2026-09-18') {
        mStatus = 'PRESENT';
        aStatus = 'ABSENT';
        note = 'Permitted by principal for dental appointment at 1:00 PM';
      }

      // Stu 10 (Zainab) excused illness on 2026-09-15
      if (student.id === 'stu_10' && date === '2026-09-15') {
        mStatus = 'EXCUSED';
        aStatus = 'EXCUSED';
        note = 'Medical excuse note submitted by parent';
      }

      // Stu 6 (Ngozi) morning late on Monday 2026-09-28
      if (student.id === 'stu_6' && date === '2026-09-28') {
        mLate = 'LATE';
        note = 'School bus delayed in traffic';
      }

      // Today (2026-09-29): Mark morning present, afternoon pending or present
      if (date === '2026-09-29') {
        if (student.id === 'stu_8') {
          mStatus = 'PRESENT';
          mLate = 'LATE';
        }
        if (student.id === 'stu_11') {
          mStatus = 'ABSENT';
          aStatus = 'ABSENT';
        }
      }

      records.push({
        id: `att_${student.id}_${date}`,
        schoolId: 'school_demo_1',
        studentId: student.id,
        classId: student.classId,
        sessionId: 'session_2026_2027',
        termId: 'term_1_2026',
        date,
        morningStatus: mStatus,
        afternoonStatus: aStatus,
        morningLateness: mLate,
        afternoonLateness: aLate,
        notes: note,
        markedByUserId: 'user_teacher_1',
        updatedAt: new Date(date + 'T14:30:00Z').toISOString(),
      });
    }
  }

  return records;
}

